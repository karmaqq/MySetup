/*                  NETLIFY ENV → FIREBASE CONFIG ÜRETİCİ                   */
/* ═══════════════════════════════════════════════════════════════════════════ */
/*  Netlify build sırasında environment variable'lardan js/firebase-config.js */
/*  dosyasını oluşturur. Netlify dashboard'da şu değişkenler tanımlı olmalı:  */
/*    FB_API_KEY, FB_AUTH_DOMAIN, FB_DATABASE_URL, FB_PROJECT_ID,           */
/*    FB_STORAGE_BUCKET, FB_SENDER_ID, FB_APP_ID                           */
/* ═══════════════════════════════════════════════════════════════════════════ */

const fs = require("fs");
const path = require("path");

const config = {
  apiKey: process.env.FB_API_KEY,
  authDomain: process.env.FB_AUTH_DOMAIN,
  databaseURL: process.env.FB_DATABASE_URL,
  projectId: process.env.FB_PROJECT_ID,
  storageBucket: process.env.FB_STORAGE_BUCKET,
  messagingSenderId: process.env.FB_SENDER_ID,
  appId: process.env.FB_APP_ID,
};

const missing = Object.entries(config).filter(([, v]) => !v);
if (missing.length) {
  console.error(
    "Missing Firebase env vars: " + missing.map(([k]) => k).join(", "),
  );
  process.exit(1);
}

const content =
  "/* --- Firebase config (auto-generated by Netlify build) --- */\n" +
  "window.__FB_CONFIG__ = " +
  JSON.stringify(config, null, 2) +
  ";\n";

const outPath = path.join(__dirname, "..", "js", "firebase-config.js");
fs.writeFileSync(outPath, content);
console.log("firebase-config.js generated from environment variables");
